// 무게 드롭다운 목록 (전 국가 통합: 0.5~30kg)
const validWeights = (function() {
    const weights = [];
    // 0.5~20.0kg: 0.5단위
    for (let w = 0.5; w <= 20.0; w += 0.5) {
        weights.push(parseFloat(w.toFixed(1)));
    }
    // 21.0~30.0kg: 1.0단위
    for (let w = 21.0; w <= 30.0; w += 1.0) {
        weights.push(w);
    }
    return weights;
})();
